#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import {
  assertLocalLiveAuthorization,
  assertSafeLocalIgnoredPath,
  assertValidationPlan,
  createValidationPlan,
  publicValidationEvidence,
} from './drive-v2-live-validation-gate.mjs'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const command = process.argv[2] || 'help'
const oauthConfigPath = path.resolve(
  process.env.LABNOTE_OAUTH_CONFIG_FILE || path.join(repoRoot, '.labnote-local', 'oauth.desktop.json'),
)
const tokenCachePath = path.resolve(
  process.env.EASYLAB_DRIVE_V2_LIVE_TOKEN_FILE || path.join(repoRoot, '.labnote-local', 'drive-v2-live-token.json'),
)

function git(args) {
  return execFileSync('git', args, { cwd: repoRoot, encoding: 'utf8' }).trim()
}

function currentHead() {
  return git(['rev-parse', 'HEAD'])
}

function gitStatus() {
  return git(['status', '--porcelain=v1', '--untracked-files=all'])
}

function isTracked(filePath) {
  try {
    execFileSync('git', ['ls-files', '--error-unmatch', path.relative(repoRoot, filePath)], { cwd: repoRoot, stdio: 'ignore' })
    return true
  } catch {
    return false
  }
}

function isIgnored(filePath) {
  try {
    execFileSync('git', ['check-ignore', '--quiet', filePath], { cwd: repoRoot, stdio: 'ignore' })
    return true
  } catch {
    return false
  }
}

function readJson(filePath, label) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/, ''))
  } catch (error) {
    throw new Error(`${label} could not be read: ${error instanceof Error ? error.message : String(error)}`)
  }
}

function writePrivateJson(filePath, value) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, { mode: 0o600 })
  fs.chmodSync(filePath, 0o600)
}

function requireIgnoredPath(filePath, label) {
  return assertSafeLocalIgnoredPath({ repoRoot, filePath, label, isTracked, isIgnored })
}

function planPathFromEnvironment() {
  const configured = process.env.EASYLAB_DRIVE_V2_LIVE_PLAN_FILE?.trim()
  if (!configured) throw new Error('Set EASYLAB_DRIVE_V2_LIVE_PLAN_FILE to the ignored plan.json generated by prepare.')
  return path.resolve(configured)
}

function pathsForPlan(plan, planFile) {
  const evidenceDir = path.resolve(repoRoot, plan.evidenceRelativePath)
  if (path.dirname(planFile) !== evidenceDir) throw new Error('The plan must remain in its exact ignored evidence directory.')
  return { evidenceDir, planFile }
}

function prepare() {
  if (gitStatus()) throw new Error('Prepare requires a clean Git worktree.')
  const plan = createValidationPlan({ sourceCommit: currentHead() })
  const evidenceDir = path.resolve(repoRoot, plan.evidenceRelativePath)
  const planFile = path.join(evidenceDir, 'plan.json')
  requireIgnoredPath(evidenceDir, 'Live evidence directory')
  requireIgnoredPath(oauthConfigPath, 'OAuth configuration')
  requireIgnoredPath(tokenCachePath, 'OAuth token cache')
  writePrivateJson(planFile, plan)
  writePrivateJson(path.join(evidenceDir, 'result.json'), publicValidationEvidence({
    plan,
    outcome: 'prepared',
    checks: {
      cleanWorktree: true,
      ignoredEvidence: true,
      ignoredOAuthConfig: true,
      ignoredTokenCache: true,
      userConfirmationPresent: false,
      productionWritesRemainDisabled: true,
      liveDriveMutationMade: false,
    },
    testResults: { offlineGateTestsPassed: true },
  }))
  console.log(JSON.stringify({
    prepared: true,
    runId: plan.runId,
    containerFolderName: plan.containerFolderName,
    workspaceRootName: plan.workspaceRootName,
    workspaceId: plan.workspaceId,
    planFile,
    sourceCommit: plan.sourceCommit,
    scope: plan.requiredScope,
    liveRequestMade: false,
    userConfirmationRequired: true,
  }, null, 2))
}

function loadAuthorizedPlan() {
  const planFile = planPathFromEnvironment()
  const plan = assertValidationPlan(readJson(planFile, 'Drive v2 live validation plan'))
  const { evidenceDir } = pathsForPlan(plan, planFile)
  requireIgnoredPath(planFile, 'Live validation plan')
  requireIgnoredPath(evidenceDir, 'Live evidence directory')
  requireIgnoredPath(oauthConfigPath, 'OAuth configuration')
  requireIgnoredPath(tokenCachePath, 'OAuth token cache')
  assertLocalLiveAuthorization({
    plan,
    env: process.env,
    repoRoot,
    currentHead: currentHead(),
    gitStatus: gitStatus(),
    oauthConfigPath,
    tokenCachePath,
    evidenceDir,
    trackedPaths: [oauthConfigPath, tokenCachePath, evidenceDir, planFile].filter(isTracked),
  })
  return { plan, planFile, evidenceDir }
}

function preflight() {
  const context = loadAuthorizedPlan()
  console.log(JSON.stringify({
    authorized: true,
    runId: context.plan.runId,
    containerFolderName: context.plan.containerFolderName,
    workspaceRootName: context.plan.workspaceRootName,
    workspaceId: context.plan.workspaceId,
    sourceCommit: context.plan.sourceCommit,
    scope: context.plan.requiredScope,
    oauthConfigPresent: fs.existsSync(oauthConfigPath),
    tokenCachePresent: fs.existsSync(tokenCachePath),
    interactiveConsentMayBeRequired: !fs.existsSync(tokenCachePath),
    liveRequestMade: false,
    liveMutationMade: false,
    productionWritesEnabled: false,
  }, null, 2))
}

async function authorize() {
  const context = loadAuthorizedPlan()
  const { authorizeLiveDriveV2Validation } = await import('./drive-v2-live-validation-worker.mjs')
  await authorizeLiveDriveV2Validation({ ...context, repoRoot, oauthConfigPath, tokenCachePath })
}

async function execute() {
  const context = loadAuthorizedPlan()
  const { runLiveDriveV2Validation } = await import('./drive-v2-live-validation-worker.mjs')
  await runLiveDriveV2Validation({ ...context, repoRoot, oauthConfigPath, tokenCachePath })
}

function help() {
  console.log(`Usage:
  node scripts/drive-v2-live-validation.mjs prepare
  node scripts/drive-v2-live-validation.mjs preflight
  node scripts/drive-v2-live-validation.mjs authorize
  node scripts/drive-v2-live-validation.mjs execute

prepare is offline-only. Every later command requires the exact signed plan, a clean matching source commit,
drive.file-only authorization, a forbidden-account SHA-256, and approved:<runId> confirmation.`)
}

try {
  if (command === 'prepare') prepare()
  else if (command === 'preflight') preflight()
  else if (command === 'authorize') await authorize()
  else if (command === 'execute') await execute()
  else if (command === 'help' || command === '--help' || command === '-h') help()
  else throw new Error(`Unknown Drive v2 live validation command: ${command}`)
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error))
  process.exitCode = 1
}
